// Package scaffold writes the files gd-sync puts in every site: .gitignore,
// .gitattributes, the settings files, GD-SYNC.md, the devcontainer, the GitHub
// workflows and the JetBrains run configurations.
//
// The templates are built into the binary. Set GD_SYNC_TEMPLATES to a folder
// to use templates from disk instead, while working on them.
package scaffold

import (
	"embed"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"sort"
	"strconv"
	"strings"

	"github.com/s-visser/gd-sync/internal/site"
	"github.com/s-visser/gd-sync/internal/ui"
)

//go:embed all:templates
var embedded embed.FS

func templates() fs.FS {
	if dir := os.Getenv("GD_SYNC_TEMPLATES"); dir != "" {
		return os.DirFS(dir)
	}
	sub, _ := fs.Sub(embedded, "templates")
	return sub
}

// All writes every scaffold file. The site's README is written only once.
func All(s *site.Site) error {
	for _, step := range []func(*site.Site) error{
		Gitignore, Gitattributes, func(s *site.Site) error { return s.Write() },
		Docs, Devcontainer, Workflows, RunConfigs,
	} {
		if err := step(s); err != nil {
			return err
		}
	}
	return nil
}

func write(s *site.Site, name, content string) error {
	p := filepath.Join(s.Repo, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, []byte(content), 0o644)
}

func Gitignore(s *site.Site) error {
	if s.Type == "astro" {
		return write(s, ".gitignore", gitignoreAstro)
	}
	return write(s, ".gitignore", gitignoreWordPress(s.Tracked, s.KeptOut()))
}

// gitignoreWordPress ignores the whole folder — the local mirror of the live
// site — except gd-sync's own files and the paths you maintain. Each
// maintained path is let back in one folder at a time, because git can't
// re-include a file whose parent folder is excluded.
func gitignoreWordPress(tracked, keptOut []string) string {
	var b strings.Builder
	b.WriteString("# Generated by gd-sync from tracked in .gd-sync.toml — run 'gd-sync scaffold' after changing it.\n")
	b.WriteString("# The folder holds the whole live site; git keeps only gd-sync's files and the\n")
	b.WriteString("# paths you maintain.\n")
	if !slices.Contains(tracked, ".") {
		b.WriteString("/*\n")
		for _, f := range gitignoreScaffold {
			b.WriteString("!/" + f + "\n")
		}
		b.WriteString("\n# Maintained paths\n")
		opened := map[string]bool{}
		for _, t := range topmost(tracked) {
			parts := strings.Split(t, "/")
			for i := 1; i < len(parts); i++ {
				dir := strings.Join(parts[:i], "/")
				if !opened[dir] {
					opened[dir] = true
					fmt.Fprintf(&b, "!/%s/\n/%s/*\n", ignoreEscape(dir), ignoreEscape(dir))
				}
			}
			fmt.Fprintf(&b, "!/%s\n", ignoreEscape(t))
		}
		b.WriteString("\n")
	}
	if len(keptOut) > 0 {
		b.WriteString("# Inside maintained paths, but kept out of git (ignore and vendor in .gd-sync.toml)\n")
		for _, p := range topmost(keptOut) {
			fmt.Fprintf(&b, "/%s\n", ignoreEscape(p))
		}
		b.WriteString("\n")
	}
	b.WriteString(gitignoreNever)
	return b.String()
}

// topmost cleans the paths and drops any that sit inside another one.
func topmost(paths []string) []string {
	var clean []string
	for _, p := range paths {
		if p = strings.Trim(path.Clean("/"+p), "/"); p != "" {
			clean = append(clean, p)
		}
	}
	sort.Strings(clean)
	var out []string
	for _, p := range clean {
		if n := len(out); n > 0 && (p == out[n-1] || strings.HasPrefix(p, out[n-1]+"/")) {
			continue
		}
		out = append(out, p)
	}
	return out
}

// ignoreEscape makes a path match literally in .gitignore.
func ignoreEscape(p string) string {
	var b strings.Builder
	for _, r := range p {
		if strings.ContainsRune(`\*?[!# `, r) {
			b.WriteRune('\\')
		}
		b.WriteRune(r)
	}
	return b.String()
}

// Gitattributes stops git from touching line endings: the server's bytes are
// the truth, and a CRLF checkout on Windows must never be deployed. Files
// listed under lfs in .gd-sync.toml go through Git LFS.
func Gitattributes(s *site.Site) error {
	var b strings.Builder
	b.WriteString("# The server's bytes are the truth — git must not rewrite line endings.\n* -text\n")
	if len(s.LFS) > 0 {
		b.WriteString("\n# Large binary files, kept in Git LFS (lfs in .gd-sync.toml)\n")
		for _, p := range s.LFS {
			fmt.Fprintf(&b, "%s filter=lfs diff=lfs merge=lfs -text\n", attrPattern(p))
		}
	}
	return write(s, ".gitattributes", b.String())
}

// attrPattern makes a path match literally, and only at the top, in
// .gitattributes. Patterns with spaces must be quoted there.
func attrPattern(p string) string {
	var b strings.Builder
	b.WriteByte('/')
	for _, r := range p {
		if strings.ContainsRune(`\*?[`, r) {
			b.WriteRune('\\')
		}
		b.WriteRune(r)
	}
	pat := b.String()
	if !strings.ContainsAny(pat, " \t\"") {
		return pat
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(pat) + `"`
}

// Docs writes GD-SYNC.md, the tool's own cheat sheet, and the site's README
// if it doesn't have one yet.
func Docs(s *site.Site) error {
	if err := write(s, "GD-SYNC.md", cheatSheet); err != nil {
		return err
	}
	if _, err := os.Stat(filepath.Join(s.Repo, "README.md")); err == nil {
		return nil
	}
	domain := strings.TrimSuffix(strings.TrimPrefix(strings.TrimPrefix(s.LiveURL, "http://"), "https://"), "/")
	kind := map[string]string{"wordpress": "WordPress", "astro": "Astro (static)"}[s.Type]
	if kind == "" {
		kind = s.Type
	}
	login := ""
	if s.Type == "wordpress" {
		// The local admin post-create.sh makes in every WordPress container.
		login = fmt.Sprintf("| Local admin | %s/wp-admin — `dev` / `dev` |\n", strings.TrimSuffix(s.LocalURL, "/"))
	}
	return write(s, "README.md", fmt.Sprintf(readme, domain, s.LiveURL, s.LocalURL, login, kind))
}

// Devcontainer copies the template for the site's type and fills in the
// site name and ports.
func Devcontainer(s *site.Site) error {
	tpl := templates()
	root := s.Type + "/.devcontainer"
	if _, err := fs.Stat(tpl, root); err != nil {
		ui.Warn("No devcontainer template for type '%s'", s.Type)
		return nil
	}
	err := fs.WalkDir(tpl, root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := fs.ReadFile(tpl, p)
		if err != nil {
			return err
		}
		content := string(b)
		if path.Base(p) == "devcontainer.json" {
			content = strings.NewReplacer(
				"__SITE__", s.Name,
				"__PORT__", strconv.Itoa(s.Port),
				"__DB_PORT__", strconv.Itoa(s.DBPort),
				"__MAIL_PORT__", strconv.Itoa(s.MailPort),
			).Replace(content)
		}
		return write(s, ".devcontainer/"+strings.TrimPrefix(p, root+"/"), content)
	})
	if err != nil {
		return err
	}
	return Env(s)
}

// Env writes .devcontainer/.env, where docker compose reads the site's
// settings from: its name, URLs, ports and PHP version.
func Env(s *site.Site) error {
	// GD_SYNC_VERSION is the gd-sync the container installs, like the workflows.
	env := fmt.Sprintf("COMPOSE_PROJECT_NAME=%s\nLIVE_URL=%s\nLOCAL_URL=%s\nGD_SYNC_VERSION=%s\n", composeName(s.Name), s.LiveURL, s.LocalURL, ToolVersion)
	switch s.Type {
	case "astro":
		env += fmt.Sprintf("ASTRO_PORT=%d\nPREVIEW_PORT=%d\n", s.Port, s.PreviewPort)
	case "wordpress":
		env += fmt.Sprintf("WP_PORT=%d\nDB_PORT=%d\nMAIL_PORT=%d\n", s.Port, s.DBPort, s.MailPort)
		if s.PHPVersion != "" {
			env += "PHP_VERSION=" + s.PHPVersion + "\n"
		}
	}
	return write(s, ".devcontainer/.env", env)
}

// composeName is the site name as Docker Compose accepts a project name:
// lowercase letters, digits, dashes and underscores. acme.nl becomes acme-nl.
func composeName(name string) string {
	return strings.Map(func(r rune) rune {
		switch {
		case r >= 'A' && r <= 'Z':
			return r + 'a' - 'A'
		case r == '-' || r == '_' || r >= '0' && r <= '9' || r >= 'a' && r <= 'z':
			return r
		}
		return '-'
	}, name)
}

// ToolVersion is the gd-sync version the workflows and the devcontainer
// install: the version of the gd-sync that wrote them, so workers, the
// container and your computer behave the same.
var ToolVersion = "latest"

func Workflows(s *site.Site) error {
	for _, name := range []string{"deploy.yml", "sync-from-server.yml", "verify-main.yml"} {
		b, err := fs.ReadFile(templates(), "github/"+name)
		if err != nil {
			return err
		}
		content := strings.ReplaceAll(string(b), "__GD_SYNC_VERSION__", ToolVersion)
		if err := write(s, ".github/workflows/"+name, content); err != nil {
			return err
		}
	}
	return nil
}

// RunConfigs adds JetBrains run configurations for the everyday commands.
// No site name in any of them — the working directory decides.
func RunConfigs(s *site.Site) error {
	for _, c := range []struct{ name, args string }{
		{"1 Sync main from server", "sync"},
		{"2 Pull database", "db"},
		{"3 Server diff", "status"},
		{"4 Merge and go live", "merge"},
		{"5 Deploy by hand", "deploy"},
	} {
		file := ".run/" + strings.ReplaceAll(c.name, " ", "_") + ".run.xml"
		if err := write(s, file, fmt.Sprintf(runConfig, c.name, c.args)); err != nil {
			return err
		}
	}
	return nil
}
